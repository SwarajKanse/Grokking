def get_mem_mb() -> tuple[float, float]:
    """Returns (current_rss_mb, peak_rss_mb) on Linux."""
    curr_mb = 0.0
    try:
        with open("/proc/self/statm", "r") as f:
            parts = f.read().split()
            pages = int(parts[1])
            curr_mb = (pages * os.sysconf("SC_PAGE_SIZE")) / (1024.0 * 1024.0)
    except Exception:
        pass
    peak_mb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024.0
    return curr_mb, peak_mb


def main():
    print("=" * 90)
    print("DIAGNOSTIC & RE-MEASUREMENT: MEMORY BREAKDOWN & LEADING-ZERO FIX")
    print("=" * 90)

    # -------------------------------------------------------------
    # PART 1: Leading-Zero Normalization Check on Pair 4
    # -------------------------------------------------------------
    print("\n--- Part 1: Leading-Zero Normalization Check (Pair 4) ---")
    s1_addr = "6201 Corporate Park Drive, Greensboro, NC"
    cand_addr = "006201 Corporate Park Drive, N/A, Greensboro, North Carolina"

    d1 = extract_digit_tokens(s1_addr)
    d2 = extract_digit_tokens(cand_addr)
    overlap = 1.0 if (d1 & d2) else 0.0
    jaccard = len(d1 & d2) / len(d1 | d2) if (d1 | d2) else 0.0

    print(f"S1 Address:      '{s1_addr}'")
    print(f"Cand Address:    '{cand_addr}'")
    print(f"S1 Digit Tokens:   {d1}")
    print(f"Cand Digit Tokens: {d2}")
    print(f"Digits Overlap:    {overlap} (Expected: 1.0)")
    print(f"Digits Jaccard:    {jaccard:.4f} (Expected: 1.0000)")

    norm_s1 = normalize_address(s1_addr)
    norm_cand = normalize_address(cand_addr)
    st1 = (norm_s1.street_number or "").lstrip("0") or ("0" if norm_s1.street_number else "")
    st2 = (norm_cand.street_number or "").lstrip("0") or ("0" if norm_cand.street_number else "")
    st_exact = 1.0 if (st1 and st1 == st2) else 0.0
    print(f"Street Num S1:   '{norm_s1.street_number}' -> normalized '{st1}'")
    print(f"Street Num Cand: '{norm_cand.street_number}' -> normalized '{st2}'")
    print(f"Street Num Exact:  {st_exact} (Expected: 1.0)")

    # -------------------------------------------------------------
    # PART 2: Memory Breakdown Analysis: Why Did Peak RSS Hit 27.48 GiB?
    # -------------------------------------------------------------
    print("\n" + "=" * 90)
    print("--- Part 2: Dissecting the 21.6 GiB Gap: Per-Object & Stage Memory ---")
    print("=" * 90)

    # Measure exact deep memory of NormalizedRecord instances
    sample_records = []
    t_obj0 = time.time()
    for i in range(10000):
        sample_records.append(
            NormalizedRecord(
                entity_id=f"S2-{i:08d}",
                country="US",
                name=normalize_name("Pediatric Associates of Western Washington Inc"),
                address=normalize_address("1126 Lombard Avenue, Suite 400, Everett, WA 98201"),
            )
        )
    gc.collect()
    curr_mb, peak_mb = get_mem_mb()
    bytes_per_record = (curr_mb * 1024 * 1024) / len(sample_records)
    print(f"Measured deep RAM for 10,000 NormalizedRecord objects: {curr_mb:.2f} MB")
    print(f"Measured bytes per NormalizedRecord in Python heap:    {bytes_per_record:.1f} bytes/record")
    print(f"Projected RAM for 10,320,219 records in cand_lookup:   {(10320219 * bytes_per_record) / (1024**3):.2f} GiB")

    del sample_records
    gc.collect()

    # -------------------------------------------------------------
    # PART 3: Real Stage-by-Stage Memory of Decoupled Phase 3
    # -------------------------------------------------------------
    print("\n" + "=" * 90)
    print("--- Part 3: Clean Decoupled Phase 3 Execution on Same 2,500-Entity Slice ---")
    print("=" * 90)

    # 1. Load the 124,633 candidate pairs generated by Phase 2
    # In experiments/val_features.parquet we have all 1.25M pairs from the full run.
    # Take the exact 2,500 entities slice pairs!
    val_feat_table = pq.read_table("experiments/val_features.parquet", columns=["source1_entity_id", "candidate_entity_id", "blocking_score", "candidate_rank", "label"])
    val_feat_df = val_feat_table.to_pandas()
    del val_feat_table

    unique_s1_all = val_feat_df["source1_entity_id"].unique()
    np.random.seed(42)
    slice_s1 = set(np.random.choice(unique_s1_all, size=2500, replace=False))
    slice_pairs_df = val_feat_df[val_feat_df["source1_entity_id"].isin(slice_s1)].copy().reset_index(drop=True)
    del val_feat_df
    gc.collect()

    print(f"Slice Candidate Pairs: {len(slice_pairs_df):,} pairs across {len(slice_s1):,} unique S1 entities.")
    unique_cands_needed = set(slice_pairs_df["candidate_entity_id"])
    print(f"Unique Candidate Entities needed for slice: {len(unique_cands_needed):,} (out of 10.3M total records in S2+S3)")

    curr_mb, peak_mb = get_mem_mb()
    print(f"Stage 1 (Slice Pairs Loaded): Current RSS = {curr_mb:.2f} MB | Peak RSS = {peak_mb:.2f} MB")

    # 2. Load Source 1 records for these 2,500 entities
    s1_df = pd.read_csv("dataset/train/train_source1.tsv", sep="\t", dtype=str).fillna("")
    s1_slice_df = s1_df[s1_df["entity_id"].isin(slice_s1)]
    del s1_df
    gc.collect()

    s1_lookup: dict[str, NormalizedRecord] = {}
    for _, row in s1_slice_df.iterrows():
        e_id = row["entity_id"]
        s1_lookup[e_id] = NormalizedRecord(
            entity_id=e_id,
            country=row["country"],
            name=normalize_name(row["business_name"]),
            address=normalize_address(row["business_address"]),
        )
    del s1_slice_df
    gc.collect()

    curr_mb, peak_mb = get_mem_mb()
    print(f"Stage 2 (S1 Records Normalized - 2.5k): Current RSS = {curr_mb:.2f} MB | Peak RSS = {peak_mb:.2f} MB")

    # 3. Load ONLY the candidate records that appear in the candidate pairs!
    # Split candidates into S2 and S3 sets
    needed_s2 = {c for c in unique_cands_needed if c.startswith("S2-")}
    needed_s3 = {c for c in unique_cands_needed if c.startswith("S3-")}
    print(f"Loading {len(needed_s2):,} S2 candidates and {len(needed_s3):,} S3 candidates from raw TSVs...")

    cand_lookup: dict[str, NormalizedRecord] = {}

    t_cand0 = time.time()
    for tsv_path, needed_set in [("dataset/train/train_source2.tsv", needed_s2), ("dataset/train/train_source3.tsv", needed_s3)]:
        # Stream TSV in chunks of 500,000, filtering ONLY matching IDs
        for chunk in pd.read_csv(tsv_path, sep="\t", dtype=str, chunksize=500000):
            matched = chunk[chunk["entity_id"].isin(needed_set)]
            if len(matched) > 0:
                e_ids = matched["entity_id"].tolist()
                names = matched["business_name"].fillna("").tolist()
                addrs = matched["business_address"].fillna("").tolist()
                ctrys = matched["country"].fillna("").tolist()
                for i in range(len(e_ids)):
                    cand_lookup[e_ids[i]] = NormalizedRecord(
                        entity_id=e_ids[i],
                        country=ctrys[i],
                        name=normalize_name(names[i]),
                        address=normalize_address(addrs[i]),
                    )

    t_cand_load = time.time() - t_cand0
    curr_mb, peak_mb = get_mem_mb()
    print(f"Stage 3 (Candidate Records Normalized - {len(cand_lookup):,} in {t_cand_load:.2f}s): Current RSS = {curr_mb:.2f} MB | Peak RSS = {peak_mb:.2f} MB")

    # 4. Feature Extraction on the Slice
    print("\nRunning feature extraction on all 124,633 pairs...")
    t_feat0 = time.time()
    slice_features_df = build_pair_features_df(slice_pairs_df, s1_lookup, cand_lookup, chunk_size=25000)
    t_feat = time.time() - t_feat0

    curr_mb, peak_mb = get_mem_mb()
    print(f"Stage 4 (Feature Extraction Complete - {len(slice_features_df):,} rows in {t_feat:.2f}s):")
    print(f"  Throughput:  {len(slice_features_df)/t_feat:,.0f} pairs/sec")
    print(f"  Current RSS: {curr_mb:.2f} MB ({curr_mb/1024:.2f} GB)")
    print(f"  Peak RSS:    {peak_mb:.2f} MB ({peak_mb/1024:.2f} GB)")

    print("\n" + "=" * 90)
    print("SUMMARY COMPARISON")
    print(f"Old Monolithic Architecture Peak RSS: 27.48 GiB (caused by 10.3M Python objects + CandidateIndex)")
    print(f"Clean Decoupled Phase 3 Peak RSS:     {peak_mb/1024:.2f} GiB (only candidates in pairs loaded)")
    print("=" * 90)


if __name__ == "__main__":
    main()
